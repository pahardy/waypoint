"""Learning objectives extracted from the official study guides."""

import re
from pathlib import Path
from typing import Literal

import pymupdf
import yaml
from pydantic import BaseModel

from waypoint_ingest.pdf_lines import Line, page_lines
from waypoint_ingest.sources import REPO_ROOT

OBJECTIVES_FILE = REPO_ROOT / "db" / "seed" / "objectives.yaml"

Exam = Literal["PSTAR", "PPAER", "FLIGHT_TEST"]


class Objective(BaseModel):
    """One learning objective, traced to its place in a source document."""

    id: str
    exam: Exam
    subject: str
    area: str
    topic: str
    text: str
    detail: str | None = None
    essential: bool = False
    ref: str | None = None
    source: str
    page: int


def load_objectives(path: Path = OBJECTIVES_FILE) -> list[Objective]:
    """Load objectives and check that ids are unique."""
    objectives = [Objective(**item) for item in yaml.safe_load(path.read_text())]
    ids = [o.id for o in objectives]
    duplicates = {i for i in ids if ids.count(i) > 1}
    if duplicates:
        raise ValueError(f"duplicate objective ids: {sorted(duplicates)}")
    return objectives


def write_objectives(objectives: list[Objective], path: Path = OBJECTIVES_FILE) -> None:
    """Write objectives as YAML."""
    path.parent.mkdir(parents=True, exist_ok=True)
    data = [o.model_dump(exclude_defaults=True) for o in objectives]
    header = "# Generated by `uv run ingest objectives`. Do not edit by hand.\n"
    path.write_text(header + yaml.safe_dump(data, sort_keys=False, allow_unicode=True))


# --- TP 12880 (PPAER) -------------------------------------------------------

PPAER_SUBJECTS = {
    "Air Law": "air-law",
    "Navigation": "navigation",
    "Meteorology": "meteorology",
    "Aeronautics - General Knowledge": "aeronautics",
}
PPAER_END = "Recommended Study Material"
NUMBERED = re.compile(r"^(\d{1,2}) (\S.*)$")
CAR_SECTION = re.compile(r"^(\d{3}\.\d{2,3}(?:\.\d+)?) (.*)$")
CAR_SUBPART = re.compile(r"^(\d{3}) [–−-] (.*)$")
AIM_REF = re.compile(
    r"TC[- ]AIM\s*[−–-]?\s*([A-Z]{3}(?: \d+(?:\.\d+)*(?: and \d+(?:\.\d+)*)?)?)"
)


class OutlineParser:
    """Walks the study guide's outline lines and collects objectives."""

    def __init__(self, exam: Exam, source: str, id_prefix: str):
        self.exam, self.source, self.id_prefix = exam, source, id_prefix
        self.subject = self.area = self.topic = self.base_topic = ""
        self.topic_ref: str | None = None
        self.heading_open = False
        self.item: Objective | None = None
        self.item_x = 0.0
        self.expected_number = 1
        self.objectives: list[Objective] = []
        self.problems: list[str] = []

    def set_topic(self, text: str, merge: bool = False) -> None:
        """Start a topic, or extend a heading that wraps onto two lines."""
        self.base_topic = f"{self.base_topic} {text}" if merge else text
        self.set_subtopic(None)

    def set_subtopic(self, text: str | None) -> None:
        """Qualify the current topic with a subheading or note."""
        if text is None:
            self.topic = self.base_topic
        elif text.startswith("("):
            self.topic = f"{self.base_topic} {text}"
        else:
            self.topic = f"{self.base_topic} ({text})"
        match = AIM_REF.search(self.topic)
        self.topic_ref = f"TC AIM {match.group(1)}" if match else None
        self.item = None
        self.expected_number = 1

    def add_item(self, line: Line, text: str, ref: str | None, number: int | None):
        """Record a new objective and check its numbering."""
        if number is not None and number != self.expected_number:
            self.problems.append(
                f"p{line.page} {self.topic!r}: expected {self.expected_number}, "
                f"got {number} {text!r}"
            )
        self.expected_number = (number or 0) + 1
        count = sum(1 for o in self.objectives if o.subject == self.subject) + 1
        self.item = Objective(
            id=f"{self.id_prefix}.{self.subject}.{count:03d}",
            exam=self.exam,
            subject=self.subject,
            area=self.area,
            topic=self.topic,
            text=text,
            essential=line.bullet,
            ref=ref or self.topic_ref,
            source=self.source,
            page=line.page,
        )
        self.item_x = line.x
        self.objectives.append(self.item)

    def continue_item(self, line: Line) -> bool:
        """Append a wrapped line to the current item if it is indented under it."""
        if self.item and line.x > self.item_x + 5:
            self.item.text = f"{self.item.text} {line.text}"
            return True
        return False


def extract_ppaer(pdf_path: Path) -> tuple[list[Objective], list[str]]:
    """Extract PPAER objectives from TP 12880. Returns objectives and problems."""
    parser = OutlineParser("PPAER", "tp12880", "ppaer")
    doc = pymupdf.open(pdf_path)
    started = False
    for page_number in range(1, doc.page_count + 1):
        for line in page_lines(doc, page_number):
            if line.size == 20 and line.bold:
                if line.text.startswith(PPAER_END) and started:
                    return parser.objectives, parser.problems
                if line.text in PPAER_SUBJECTS:
                    started = True
                    parser.subject = PPAER_SUBJECTS[line.text]
                continue
            if not started or line.size < 12:
                continue
            parse_ppaer_line(parser, line)
    return parser.objectives, parser.problems


def parse_ppaer_line(parser: OutlineParser, line: Line) -> None:
    """Classify one outline line and update the parser."""
    was_heading = parser.heading_open
    parser.heading_open = False
    if line.bold and line.size == 16:
        parser.area = line.text
        parser.set_topic("")
    elif line.bold and line.size >= 13:
        parser.set_topic(line.text, merge=was_heading)
        parser.heading_open = True
    elif match := CAR_SECTION.match(line.text):
        parser.add_item(line, match.group(2), f"CAR {match.group(1)}", None)
    elif match := CAR_SUBPART.match(line.text):
        parser.set_topic(f"CAR {match.group(1)} {match.group(2)}")
    elif match := NUMBERED.match(line.text):
        parser.add_item(line, match.group(2), None, int(match.group(1)))
    elif not parser.continue_item(line):
        parser.set_subtopic(line.text)


# --- TP 11919 (PSTAR) -------------------------------------------------------

PSTAR_SECTION = re.compile(r"^(\d{1,2})\.0 (.+)$")
PSTAR_QUESTION = re.compile(r"^(\d{1,2})\.(\d{2})\b")
ANSWER_KEY_LINE = re.compile(r"^\s*(\d{1,2}\.\d{2})\s+[1-4]", re.MULTILINE)


def extract_pstar(
    pdf_path: Path, answer_key_path: Path
) -> tuple[list[Objective], list[str]]:
    """One objective per TP 11919 section, checked against the answer key."""
    doc = pymupdf.open(pdf_path)
    sections: dict[int, dict] = {}
    for page_number in range(1, doc.page_count + 1):
        for line in page_lines(doc, page_number, columns=1):
            if line.size != 11 or line.x > 80:
                continue
            if line.bold and (match := PSTAR_SECTION.match(line.text)):
                number = int(match.group(1))
                if number in sections:
                    return pstar_objectives(sections, answer_key_path)
                title = match.group(2).title().replace("And", "and")
                sections[number] = {"title": title, "page": page_number, "ids": []}
            elif not line.bold and (match := PSTAR_QUESTION.match(line.text)):
                sections[int(match.group(1))]["ids"].append(match.group(0))
    return pstar_objectives(sections, answer_key_path)


def pstar_objectives(
    sections: dict[int, dict], answer_key_path: Path
) -> tuple[list[Objective], list[str]]:
    """Build section objectives and compare question ids with the answer key."""
    key_text = "".join(page.get_text() for page in pymupdf.open(answer_key_path))
    key_ids = set(ANSWER_KEY_LINE.findall(key_text))
    guide_ids = {qid for section in sections.values() for qid in section["ids"]}
    problems = [f"in answer key only: {i}" for i in sorted(key_ids - guide_ids)]
    problems += [f"in guide only: {i}" for i in sorted(guide_ids - key_ids)]
    objectives = []
    for number, section in sorted(sections.items()):
        ids = section["ids"]
        objectives.append(
            Objective(
                id=f"pstar.regulations.{number:03d}",
                exam="PSTAR",
                subject="regulations",
                area="Aviation Regulations",
                topic=section["title"],
                text=section["title"],
                detail=f"{len(ids)} questions, {ids[0]} to {ids[-1]}",
                ref=f"TP 11919 section {number}.0",
                source="tp11919",
                page=section["page"],
            )
        )
    return objectives, problems


# --- TP 13723 (Flight Test Guide) -------------------------------------------

EXERCISE = re.compile(r"^Ex\. ?(\d{1,2}) (.+)$")
TEST_ITEM = re.compile(r"^([A-Z])(?:\.(\d)?|\s+-)\s+(.+)$")
SMALL_CAPS_SPLIT = re.compile(r"^([A-Z]) ([A-Z]+)$")
FLIGHT_TEST_END = "Tips on How to Pass the Flight Test"
SECTION_LABELS = ("Aim", "Description", "Performance Criteria")


def extract_flight_test(pdf_path: Path) -> tuple[list[Objective], list[str]]:
    """One objective per flight test item (for example Ex. 2 A), with its aim.

    An exercise without lettered items is itself one item. Lettered items
    without their own aim inherit the exercise aim.
    """
    doc = pymupdf.open(pdf_path)
    objectives: list[Objective] = []
    exercises: list[Objective] = []
    exercise: Objective | None = None
    current: Objective | None = None
    mode = ""
    for page_number in range(1, doc.page_count + 1):
        for line in page_lines(doc, page_number, columns=1):
            if exercise and line.text.startswith(FLIGHT_TEST_END):
                return finish_flight_test(objectives, exercises)
            heading = line.bold and line.size >= 12
            if heading and line.size == 14 and (match := EXERCISE.match(line.text)):
                exercise = current = exercise_item(match, line.page)
                objectives.append(current)
                exercises.append(current)
                mode = "title"
            elif exercise and heading and (match := TEST_ITEM.match(line.text)):
                if exercise in objectives:
                    objectives.remove(exercise)
                current = lettered_item(exercise, match, line.page)
                objectives.append(current)
                mode = "title"
            elif current and line.text in SECTION_LABELS:
                mode = line.text
            elif current and mode == "title" and heading and current is not exercise:
                current.text = f"{current.text} {line.text}"
            elif current and mode == "Aim":
                current.detail = f"{current.detail or ''} {line.text}".strip()
    return finish_flight_test(objectives, exercises)


def exercise_item(match: re.Match, page: int) -> Objective:
    """An exercise heading, for example "Ex. 9 Steep Turn"."""
    number, title = int(match.group(1)), match.group(2)
    if split := SMALL_CAPS_SPLIT.match(title):
        title = (split.group(1) + split.group(2)).capitalize()
    return Objective(
        id=f"flight-test.ex{number:02d}",
        exam="FLIGHT_TEST",
        subject="flight-test",
        area="Flight Test Items",
        topic=f"Ex. {number} {title}",
        text=title,
        ref=f"TP 13723 Ex. {number}",
        source="tp13723",
        page=page,
    )


def lettered_item(exercise: Objective, match: re.Match, page: int) -> Objective:
    """A lettered item within an exercise, for example "A. Normal Takeoff"."""
    letter, part = match.group(1), match.group(2)
    label = f"{letter}.{part}" if part else letter
    return exercise.model_copy(
        update={
            "id": f"{exercise.id}{letter.lower()}{part or ''}",
            "text": match.group(3),
            "detail": None,
            "ref": f"{exercise.ref} {label}",
            "page": page,
        }
    )


def finish_flight_test(
    objectives: list[Objective], exercises: list[Objective]
) -> tuple[list[Objective], list[str]]:
    """Replace items that have sub-items (B by B.1, B.2) and fill missing aims.

    An item without its own aim takes the aim of its nearest parent.
    """
    ids = [o.id for o in objectives]
    parents = {i for i in ids if any(j != i and j.startswith(i) for j in ids)}
    aims = {o.id: o.detail for o in [*exercises, *objectives] if o.detail}
    leaves = [o for o in objectives if o.id not in parents]
    for objective in leaves:
        if not objective.detail:
            parent = max((i for i in aims if objective.id.startswith(i)), key=len)
            objective.detail = aims[parent]
    return leaves, []


def extract_all(raw_dir: Path) -> tuple[list[Objective], list[str]]:
    """Extract objectives for every exam from the acquired study guides."""
    pstar, pstar_problems = extract_pstar(
        raw_dir / "tp11919" / "tp11919.pdf",
        raw_dir / "tp11919-answers" / "tp11919-answers.pdf",
    )
    ppaer, ppaer_problems = extract_ppaer(raw_dir / "tp12880" / "tp12880.pdf")
    flight, flight_problems = extract_flight_test(raw_dir / "tp13723" / "tp13723.pdf")
    problems = pstar_problems + ppaer_problems + flight_problems
    return pstar + ppaer + flight, problems
